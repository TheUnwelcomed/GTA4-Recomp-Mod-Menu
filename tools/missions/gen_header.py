"""Write gta4_mission_pass.h: the mission scripts (for Bring Your Own Ride,
which answers only them) and, for IV's missions, how to complete each one
(table.py). usage: gen_header.py <scripts dir with IV/ TLAD/ TBOGT/> <out.h>"""
import os, re, sys, glob, struct
sys.path.insert(0, os.path.dirname(__file__))
import table

root, out = sys.argv[1:3]
mission = re.compile(r'.*\d[a-z]?$')
names = set()
for ep in ('IV', 'TLAD', 'TBOGT'):
    for f in glob.glob(os.path.join(root, ep, '*.txt')):
        n = os.path.basename(f)[:-4]
        if mission.match(n) and n != 'gxt':
            names.add(n)
keys = sorted({table.joaat(n) for n in names})
rows, missing = table.build(os.path.join(root, 'IV'))

def f32(v):
    return struct.unpack('<f', struct.pack('<f', v))[0]

lines = []
w = lines.append
w('// Generated by tools/missions/gen_header.py from the decompiled GTA IV scripts:')
w('// do not edit. %d mission scripts (IV, TLAD, TBOGT); %d IV missions completable' % (len(keys), len(rows)))
w('// (%d by Rockstar\'s debug pass key, %d by their stage variables); not: %s.' % (
    sum(r[2][0] == 'key' for r in rows), sum(r[2][0] == 'stage' for r in rows), ' '.join(m[0] for m in missing)))
w('#pragma once')
w('')
w('#include <algorithm>')
w('#include <array>')
w('#include <cstdint>')
w('#include <string_view>')
w('')
w('namespace gta4::missions {')
w('')
w('// joaat of every mission script\'s name (a name ending in a digit: roman1,')
w('// vlad3, gerry3b, brian_2...), sorted. The ambient scripts (carwash,')
w('// tollbooth, taxi, the friends\' activities, dates) are not among them.')
w('inline constexpr std::array<uint32_t, %d> kMissionScripts = {{' % len(keys))
for i in range(0, len(keys), 8):
    w('    ' + ' '.join('0x%08Xu,' % k for k in keys[i:i + 8]))
w('}};')
w('inline bool IsMissionScript(uint32_t key) {')
w('  return std::binary_search(kMissionScripts.begin(), kMissionScripts.end(), key);')
w('}')
w('')
w('struct StaticValue {')
w('  uint16_t index;  // the static (l_U<index>), four bytes each from the statics\' base')
w('  bool is_float;')
w('  int32_t i;')
w('  float f;')
w('};')
w('struct Pass {')
w('  uint32_t key;  // joaat(name)')
w('  std::string_view name;')
w('  bool by_key;   // Rockstar\'s debug pass: IS_KEYBOARD_KEY_[JUST_]PRESSED(31) answered yes')
w('  uint8_t write_count;')
w('  std::array<StaticValue, 6> writes;     // stage: these set, outermost first')
w('  uint8_t signature_count;')
w('  std::array<StaticValue, 8> signature;  // set once at start: finds the statics')
w('};')

def sv(i, v):
    if isinstance(v, float):
        return '{%d, true, 0, %sf}' % (i, repr(f32(v)) if '.' in repr(f32(v)) or 'e' in repr(f32(v)) else repr(f32(v)) + '.0')
    return '{%d, false, %d, 0.0f}' % (i, v)

rows = sorted(rows)
w('inline constexpr std::array<Pass, %d> kPasses = {{' % len(rows))
for key, n, (kind, writes), sig in rows:
    writes = writes if kind == 'stage' else []
    sig = sig or []
    w('    {0x%08Xu, "%s", %s, %d, {{%s}}, %d, {{%s}}},' % (
        key, n, 'true' if kind == 'key' else 'false', len(writes), ', '.join(sv(i, v) for i, v in writes),
        len(sig), ', '.join(sv(i, v) for i, v in sig)))
w('}};')
w('inline const Pass* FindPass(uint32_t key) {')
w('  const auto it = std::lower_bound(kPasses.begin(), kPasses.end(), key,')
w('                                   [](const Pass& p, uint32_t k) { return p.key < k; });')
w('  return it != kPasses.end() && it->key == key ? &*it : nullptr;')
w('}')
w('')
w('}  // namespace gta4::missions')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote %s: %d mission scripts, %d passes' % (out, len(keys), len(rows)))
